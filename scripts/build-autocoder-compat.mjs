import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

// Rebuild after reviewing an installed Responses upgrade. esbuild bundles its
// sources unchanged and redirects only the mathjs import to our solver adapter.
const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(join(root, 'package.json'));
const responsesManifest = require.resolve('@iqb/responses/package.json');
const responsesRoot = dirname(responsesManifest);
assert.equal(require('@iqb/responses/package.json').version, '5.4.0');
assert.equal(require('mathjs/package.json').version, '12.4.3');
const output = join(root, 'apps/backend/src/app/database/services/coding/generated/autocoder-compatibility-engine.js');
const mathAdapter = join(root, 'apps/backend/src/app/database/services/coding/autocoder-solver-math.ts');
let redirectedImports = 0;
const result = await build({
  absWorkingDir: root,
  entryPoints: [require.resolve('@iqb/responses/coding-scheme-factory')],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  write: false,
  external: ['@iqbspecs/coding-scheme'],
  banner: { js: '// Generated by node scripts/build-autocoder-compat.mjs; do not edit.\n' +
    '// Engine: @iqb/responses 5.4.0, IQB, CC0-1.0. Only solver math is scoped to\n' +
    '// autocoder-solver-math.ts / mathjs 12.4.3 (Apache-2.0), preserving 5.2.0 behaviour.' },
  plugins: [{
    name: 'isolated-legacy-solver-math',
    setup(builder) {
      builder.onResolve({ filter: /^mathjs$/ }, args => {
        if (args.importer.startsWith(responsesRoot + sep)) {
          redirectedImports += 1;
          return { path: mathAdapter };
        }
        return { path: 'mathjs', external: true };
      });
    }
  }]
});
assert.equal(redirectedImports, 1, 'Review the Responses dependency graph before changing this adapter');
const content = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  assert.equal(await readFile(output, 'utf8'), content,
    'Stale compatibility bundle: run node scripts/build-autocoder-compat.mjs');
  console.log('PASS: generated engine matches installed Responses 5.4.0 and isolated solver adapter');
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, content);
}
